/** All exercise names sorted alphabetically. */
export function allExerciseNames(): string[] {
  return Object.keys(EXERCISES).sort((a, b) => a.localeCompare(b))
}

/** Group exercises by category, in the canonical category order. */
export function exercisesByCategory(): Array<{
  category: ExerciseCategory
  items: ExerciseDef[]
}> {
  const map = new Map<ExerciseCategory, ExerciseDef[]>()
  for (const ex of Object.values(EXERCISES)) {
    if (!map.has(ex.category)) map.set(ex.category, [])
    map.get(ex.category)!.push(ex)
  }
  return Array.from(map.entries())
    .map(([category, items]) => ({
      category,
      items: items.sort((a, b) => a.name.localeCompare(b.name)),
    }))
    .sort((a, b) => a.category.localeCompare(b.category))
}

/**
 * Lookup. Returns a fallback def for unknown names so the UI can render
 * historical entries even if the catalog changes.
 */
export function getExerciseDef(name: string): ExerciseDef {
  return (
    EXERCISES[name] ?? {
      name,
      priority: 'secondary',
      category: 'Other',
      restSec: 90,
      targetSets: 3,
      targetReps: '8-12',
      targetRIR: '1-2',
      isBarbell: false,
      cues: [],
      videoSearchQuery: yt(`${name} form`),
    }
  )
}

export function searchExercises(query: string): ExerciseDef[] {
  const q = query.trim().toLowerCase()
  const all = Object.values(EXERCISES)
  if (!q) return all.sort((a, b) => a.name.localeCompare(b.name))
  return all
    .filter((e) => e.name.toLowerCase().includes(q))
    .sort((a, b) => a.name.localeCompare(b.name))
}
